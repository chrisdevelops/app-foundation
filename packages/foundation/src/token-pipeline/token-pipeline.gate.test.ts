// Gate tests for #19: the token pipeline writes generated/tokens.css through
// the profile plugin (TOK-111, TOK-112, TOK-115 to TOK-118; gates 1 to 4 of
// the token profile spec; ADR 0002 items 1, 3 and 8; ADR 0004 decisions 5
// and 7; spike #7 results 5, 8, 10, 12 and 13).
//
// Contract (input and output):
// - Input: a resolver (`tokens/ui.resolver.json`) plus `*.tokens.json` files,
//   laid out as in packages/foundation: shared tokens in `tokens/`, component
//   tokens in `src/components/<block>/`.
// - The system: `tz build` with packages/foundation/terrazzo.config.ts. The
//   gates copy that config unchanged next to a fixture token system in a
//   build folder below packages/foundation/node_modules/.cache/ and run the
//   `tz` bin of the @terrazzo/cli that packages/foundation declares there
//   (see test-support/token-build.ts).
//   So the config must use paths relative to the package root and import its
//   plugins by package name.
// - Output: `generated/tokens.css`, or a non-zero exit (the error format is
//   hardened in #20).
// - The fixture system (test-support/fixture-system/) is kept apart from the
//   real foundation tokens. Its committed expected output is
//   test-support/expected-tokens.css.txt (gate 1); the `.txt` name keeps
//   Prettier away from it, since Prettier would wrap the long lines.
