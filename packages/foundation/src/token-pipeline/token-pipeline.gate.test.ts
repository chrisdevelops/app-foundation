/** TOK-118 as amended by ADR 0002 item 8. */
const generatedHeader = '/* GENERATED by tz build. Edit the source *.tokens.json files, never this file. */';

const themeContexts = ['light', 'dark', 'light-high-contrast', 'dark-high-contrast'] as const;

/** Where a block of tokens.css applies: the context it carries, as the themes table defines. */
type BlockContext =
  | 'root'
  | 'dark'
  | 'light-high-contrast'
  | 'dark-high-contrast'
  | 'density:comfortable'
  | `data-theme:${(typeof themeContexts)[number]}`
  | 'unknown';

const buildTimeoutMs = 240_000;

// ---------- the fixture system, read without the pipeline under test

const fixtureResolver = readResolver(fixtureSystemDir);
const fixtureFiles = resolverFiles(fixtureResolver);

function filesOfSet(name: string): readonly string[] {
  return fixtureFiles.sets.get(name) ?? [];
}

function filesOfContext(modifier: string, context: string): readonly string[] {
  return fixtureFiles.contexts.get(modifier)?.get(context) ?? [];
}

function tokensOfFiles(files: readonly string[]): SourceToken[] {
  return files.flatMap((file) => readTokenFile(fixtureSystemDir, file));
}

/** The files that make up each block context of the fixture. */
function filesForBlockContext(context: BlockContext): readonly string[] {
  switch (context) {
    case 'root':
      return [
        ...filesOfSet('ref'),
        ...filesOfSet('sys'),
        ...filesOfContext('theme', 'light'),
        ...filesOfContext('density', 'compact'),
        ...filesOfSet('components'),
      ];
    case 'dark':
    case 'light-high-contrast':
    case 'dark-high-contrast':
      return filesOfContext('theme', context);
    case 'density:comfortable':
      return filesOfContext('density', 'comfortable');
    case 'unknown':
      return [];
    default:
      return filesOfContext('theme', context.slice('data-theme:'.length));
  }
}

const allFixtureFiles = [
  ...[...fixtureFiles.sets.values()].flat(),
  ...[...fixtureFiles.contexts.values()].flatMap((contexts) => [...contexts.values()].flat()),
];
const allFixtureTokens = tokensOfFiles(allFixtureFiles);
const allFixtureLeaves = new Set(allFixtureTokens.map((token) => token.leaf));

/** The component tokens the fixture must carry, each with `__` (gate 2; spike #7 result 10). */
const fixtureComponentLeaves = ['ui-button__color-bg-primary-default', 'ui-dialog__trigger__color-fg-default'];

// ---------- block classification (themes table, TOK-059 to TOK-063, TOK-116)

const contrastAttributeSelector = /^(:root)?\[data-contrast="more"\]$/;
const dataThemeSelector = /^\[data-theme="([a-z-]+)"\]$/;

/** True when every `@media` prelude is only `(feature: value)` terms joined by `and`. */
function hasOnlySimpleMediaQueries(block: TokenCssBlock): boolean {
  return mediaQueriesOf(block).every(
    (query) =>
      query
        .replace(/^@media/, '')
        .replace(/\(\s*[a-z-]+\s*:\s*[a-z-]+\s*\)/g, '')
        .replace(/\band\b/g, '')
        .trim() === '',
  );
}

function classifyBlock(block: TokenCssBlock): BlockContext {
  if (!hasOnlySimpleMediaQueries(block)) return 'unknown';
  if (block.atRules.some((atRule) => !atRule.startsWith('@media') && atRule !== '@layer tokens')) return 'unknown';
  const features = mediaFeaturesOf(block);
  if ([...features.keys()].some((feature) => feature !== 'prefers-color-scheme' && feature !== 'prefers-contrast')) {
    return 'unknown';
  }
  const scheme = features.get('prefers-color-scheme');
  const contrast = features.get('prefers-contrast');
  if (contrast !== undefined && contrast !== 'more') return 'unknown';
  if (scheme !== undefined && scheme !== 'light' && scheme !== 'dark') return 'unknown';
  const selector = block.selector;

  const theme = dataThemeSelector.exec(selector)?.[1];
  if (theme !== undefined) {
    return features.size === 0 && (themeContexts as readonly string[]).includes(theme)
      ? (`data-theme:${theme}` as BlockContext)
      : 'unknown';
  }
  if (selector === '[data-density="comfortable"]') return features.size === 0 ? 'density:comfortable' : 'unknown';

  const highContrast =
    (contrast === 'more' && selector === ':root') ||
    (contrast === undefined && contrastAttributeSelector.test(selector));
  if (highContrast) return scheme === 'dark' ? 'dark-high-contrast' : 'light-high-contrast';
  if (selector !== ':root') return 'unknown';
  if (scheme === 'dark') return 'dark';
  return features.size === 0 ? 'root' : 'unknown';
}

// ---------- builds (run once each, on first use)

let fixtureBuild: TokenBuildResult | undefined;
let secondFixtureBuild: TokenBuildResult | undefined;

function getFixtureBuild(): TokenBuildResult {
  fixtureBuild ??= buildTokenSystem({ sourceDir: fixtureSystemDir });
  return fixtureBuild;
}

/** The fixture build's tokens.css; fails the test with the build output when the build did not write it. */
function getFixtureTokensCss(): string {
  const build = getFixtureBuild();
  expect(build.run.exitCode, describeBuild(build)).toBe(0);
  expect(build.tokensCss, `generated/tokens.css was not written. ${describeBuild(build)}`).toBeDefined();
  return (build.tokensCss ?? Buffer.alloc(0)).toString('utf8');
}

function getFixtureBlocks(): readonly TokenCssBlock[] {
  const parsed = parseTokenCss(getFixtureTokensCss());
  expect(parsed.problems, 'tokens.css must hold only at-rules, style rules and declarations').toEqual([]);
  return parsed.blocks;
}

function blocksOf(context: BlockContext): TokenCssBlock[] {
  return getFixtureBlocks().filter((block) => classifyBlock(block) === context);
}

function declaredNamesOf(blocks: readonly TokenCssBlock[]): string[] {
  return blocks.flatMap((block) => block.declarations.map((declaration) => declaration.name));
}

function expectedNamesOf(context: BlockContext): string[] {
  return tokensOfFiles(filesForBlockContext(context))
    .map((token) => `--${token.leaf}`)
    .sort();
}

/** Asserts a context has at least one block, and that its blocks declare exactly the tokens of its files. */
function expectContextDeclaresItsTokens(context: BlockContext): void {
  const blocks = blocksOf(context);
  expect(blocks.length, `tokens.css must have a selector block for the ${context} context`).toBeGreaterThan(0);
  const names = declaredNamesOf(blocks);
  expect(new Set(names).size, `the ${context} context must declare each variable once`).toBe(names.length);
  expect([...names].sort(), `the ${context} context must declare exactly the tokens of its files`).toEqual(
    expectedNamesOf(context),
  );
}

afterAll(() => {
  removeTokenBuildDirs();
});

describe('token pipeline: the fixture system builds into generated/tokens.css', { timeout: buildTimeoutMs }, () => {
  // TOK-112, ADR 0004 decision 5, spike #7 result 10. TOK-001, TOK-011: the
  // DTCG fixture builds with Terrazzo's own parser, no custom parser.
  it('TOK-112: plugin-css is in the config, and with skipBuild: true the profile plugin writes the only CSS file, generated/tokens.css', async () => {
    let config: { readonly plugins?: readonly { readonly name?: unknown }[] };
    try {
      config = (
        (await import(/* @vite-ignore */ pathToFileURL(foundationTerrazzoConfigPath).href)) as {
          default: typeof config;
        }
      ).default;
    } catch (error) {
      throw new Error(`packages/foundation/terrazzo.config.ts must exist and load: ${(error as Error).message}`, {
        cause: error,
      });
    }
    const pluginNames = (config.plugins ?? []).map((plugin) => plugin.name);
    expect(pluginNames, 'the config must run @terrazzo/plugin-css for its transforms').toContain(
      '@terrazzo/plugin-css',
    );
    expect(pluginNames.length, 'the config must also run the profile plugin').toBeGreaterThan(1);

    const build = getFixtureBuild();
    expect(build.run.exitCode, describeBuild(build)).toBe(0);
    const writtenCssFiles = [...build.filesAfter.keys()].filter(
      (file) => file.endsWith('.css') && !build.filesBefore.has(file),
    );
    expect(writtenCssFiles, 'plugin-css must not write its own CSS file (skipBuild: true)').toEqual([
      'generated/tokens.css',
    ]);
  });

  // TOK-054
  it('TOK-054: the build writes only into generated/ and leaves every source file unchanged', () => {
    const build = getFixtureBuild();
    expect(build.run.exitCode, describeBuild(build)).toBe(0);
    const outsideGenerated = [...build.filesAfter.entries()]
      .filter(([file, hash]) => build.filesBefore.get(file) !== hash)
      .map(([file]) => file)
      .filter((file) => !file.startsWith('generated/'));
    const removed = [...build.filesBefore.keys()].filter((file) => !build.filesAfter.has(file));
    expect(outsideGenerated, 'files written or changed outside generated/').toEqual([]);
    expect(removed, 'files removed by the build').toEqual([]);
  });

  // TOK-118 (ADR 0002 item 8), TOK-111 (tokens.css part)
  it('TOK-118: line 1 of tokens.css is exactly the generated header', () => {
    const firstLine = getFixtureTokensCss().split('\n')[0];
    expect(firstLine).toBe(generatedHeader);
  });

  // TOK-156 (gate 1)
  it('TOK-156: tokens.css for the fixture system matches the committed expected file byte for byte', () => {
    const css = getFixtureTokensCss();
    // A Windows checkout may turn the expected file's line ends into CRLF; the pipeline writes LF.
    const expected = readFileSync(expectedFixtureTokensCssPath, 'utf8').replace(/\r\n/g, '\n');
    expect(css.includes('\r'), 'tokens.css must use LF line ends').toBe(false);
    expect(css).toBe(expected);
  });

  // TOK-156 (gate 1): the output depends only on the token files, not on the folder or the run
  it('TOK-156: two builds of the fixture system in different folders give identical bytes', () => {
    const first = getFixtureBuild();
    secondFixtureBuild ??= buildTokenSystem({ sourceDir: fixtureSystemDir });
    expect(first.run.exitCode, describeBuild(first)).toBe(0);
    expect(secondFixtureBuild.run.exitCode, describeBuild(secondFixtureBuild)).toBe(0);
    expect(first.buildDir).not.toBe(secondFixtureBuild.buildDir);
    expect(first.tokensCss, 'first build wrote generated/tokens.css').toBeDefined();
    expect(secondFixtureBuild.tokensCss, 'second build wrote generated/tokens.css').toBeDefined();
    expect(Buffer.compare(first.tokensCss ?? Buffer.alloc(0), secondFixtureBuild.tokensCss ?? Buffer.alloc(1))).toBe(0);
  });
});

describe('token pipeline: variable names (gate 2)', { timeout: buildTimeoutMs }, () => {
  // TOK-157, TOK-012, TOK-115
  it('TOK-157: every CSS variable is -- plus a leaf key that appears verbatim in a source file', () => {
    const names = new Set(declaredNamesOf(getFixtureBlocks()));
    expect(names.size, 'tokens.css must declare variables').toBeGreaterThan(0);
    const sourceTexts = allFixtureFiles.map((file) => readFileSync(join(fixtureSystemDir, ...file.split('/')), 'utf8'));
    for (const name of names) {
      expect(name, 'every declaration must be a custom property').toMatch(/^--/);
      const leaf = name.slice(2);
      expect(allFixtureLeaves.has(leaf), `${name} must be -- plus a leaf key of the fixture`).toBe(true);
      expect(
        sourceTexts.some((text) => text.includes(`"${leaf}":`)),
        `${leaf} must appear verbatim as a key in a source file`,
      ).toBe(true);
    }
  });

  // TOK-157, TOK-012
  it('TOK-157: every leaf key of the fixture has its variable', () => {
    const names = new Set(declaredNamesOf(getFixtureBlocks()));
    const missing = [...allFixtureLeaves].filter((leaf) => !names.has(`--${leaf}`));
    expect(missing, 'leaf keys without a CSS variable').toEqual([]);
  });

  // TOK-157, TOK-115, spike #7 result 10: plugin-css's own build drops `_`
  it('TOK-115: component variables keep the __ of their leaf keys exactly', () => {
    const css = getFixtureTokensCss();
    const names = new Set(declaredNamesOf(getFixtureBlocks()));
    for (const leaf of fixtureComponentLeaves) {
      expect(allFixtureLeaves.has(leaf), `fixture precondition: ${leaf} is a fixture token`).toBe(true);
      expect(names.has(`--${leaf}`), `tokens.css must declare --${leaf}`).toBe(true);
      for (const mangled of [leaf.replace(/__/g, '-'), leaf.replace(/__/g, '_'), leaf.replace(/__/g, '')]) {
        expect(css.includes(`--${mangled}:`), `tokens.css must not declare --${mangled}`).toBe(false);
      }
    }
  });
});

describe(
  'token pipeline: one selector block per context, inside @layer tokens (gate 3)',
  { timeout: buildTimeoutMs },
  () => {
    // TOK-158, TOK-071, TOK-116
    it('TOK-158: every selector block sits inside @layer tokens, and only @layer tokens and @media wrap blocks', () => {
      const blocks = getFixtureBlocks();
      expect(blocks.length).toBeGreaterThan(0);
      for (const block of blocks) {
        expect(block.atRules, `block ${block.selector} must be inside @layer tokens`).toContain('@layer tokens');
        for (const atRule of block.atRules) {
          expect(
            atRule === '@layer tokens' || atRule.startsWith('@media'),
            `block ${block.selector} is wrapped in ${atRule}`,
          ).toBe(true);
        }
      }
    });

    // TOK-116, ADR 0002 item 8
    it('TOK-116: every block belongs to one context of the themes table or to one [data-theme] block', () => {
      const unknown = getFixtureBlocks()
        .filter((block) => classifyBlock(block) === 'unknown')
        .map((block) => [...block.atRules, block.selector].join(' > '));
      expect(unknown, 'blocks that map to no context').toEqual([]);
    });

    // TOK-059, TOK-002: all three tiers in the default permutation
    it('TOK-059: the light context is :root with no media query, and declares every token of the default light and compact permutation', () => {
      expectContextDeclaresItsTokens('root');
      const tiers = new Set(tokensOfFiles(filesForBlockContext('root')).map((token) => token.tier));
      expect([...tiers].sort(), 'fixture precondition: the default permutation has all three tiers').toEqual([
        'component',
        'primitive',
        'semantic',
      ]);
    });

    // TOK-060, TOK-065
    it('TOK-060: the dark context is :root inside @media (prefers-color-scheme: dark) and declares the dark theme tokens', () => {
      expectContextDeclaresItsTokens('dark');
    });

    // TOK-061
    it('TOK-061: the light high contrast context uses the contrast media query or [data-contrast="more"], with the light scheme', () => {
      expectContextDeclaresItsTokens('light-high-contrast');
    });

    // TOK-062
    it('TOK-062: the dark high contrast context uses the contrast media query or [data-contrast="more"], with the dark scheme', () => {
      expectContextDeclaresItsTokens('dark-high-contrast');
    });

    // TOK-063
    it('TOK-063: the comfortable density context is [data-density="comfortable"] and declares the comfortable density tokens', () => {
      expectContextDeclaresItsTokens('density:comfortable');
    });

    // TOK-066, TOK-067, TOK-116, ADR 0002 item 8
    it.each(themeContexts)(
      'TOK-067: [data-theme="%s"] has its own block that mirrors the declarations of that theme context',
      (theme) => {
        const context = `data-theme:${theme}` as BlockContext;
        expectContextDeclaresItsTokens(context);
        const mirrored = theme === 'light' ? 'root' : (theme as BlockContext);
        const themeNames = new Set(expectedNamesOf(context));
        const valuesOf = (ofContext: BlockContext): Map<string, string> =>
          new Map(
            blocksOf(ofContext)
              .flatMap((block) => block.declarations)
              .filter((declaration) => themeNames.has(declaration.name))
              .map((declaration) => [declaration.name, declaration.value]),
          );
        expect(valuesOf(context), `[data-theme="${theme}"] must give the same values as the ${mirrored} block`).toEqual(
          valuesOf(mirrored),
        );
      },
    );

    // TOK-036, TOK-040
    it('TOK-036: theme and density blocks contain only semantic tokens', () => {
      const contexts: BlockContext[] = [
        'dark',
        'light-high-contrast',
        'dark-high-contrast',
        'density:comfortable',
        ...themeContexts.map((theme) => `data-theme:${theme}` as BlockContext),
      ];
      for (const context of contexts) {
        const blocks = blocksOf(context);
        expect(blocks.length, `tokens.css must have a block for ${context}`).toBeGreaterThan(0);
        for (const name of declaredNamesOf(blocks)) {
          expect(name.startsWith('--ui-ref-'), `${context} must not declare the primitive ${name}`).toBe(false);
          expect(name.includes('__'), `${context} must not declare the component token ${name}`).toBe(false);
        }
      }
    });
  },
);

describe('token pipeline: source comments (gate 4)', { timeout: buildTimeoutMs }, () => {
  const sourceCommentPattern = /^ ([a-z0-9][a-z0-9./_-]*\.tokens\.json)#([^\s#]+) $/;

  // TOK-159, TOK-117, spike #7 result 13
  it('TOK-159: every declaration ends with /* <file>#<token.path> */ that resolves to that token in that file', () => {
    const blocks = getFixtureBlocks();
    const build = getFixtureBuild();
    for (const block of blocks) {
      for (const declaration of block.declarations) {
        const where = `line ${declaration.line} (${declaration.name})`;
        expect(declaration.trailingComment, `${where} must have a trailing source comment`).toBeDefined();
        expect(declaration.commentEndsLine, `${where}: the source comment must end the line`).toBe(true);
        const match = sourceCommentPattern.exec(declaration.trailingComment ?? '');
        expect(
          match,
          `${where}: comment must be /* <file>#<token.path> */, got /*${declaration.trailingComment}*/`,
        ).not.toBeNull();
        const [, file = '', tokenPath = ''] = match ?? [];
        expect(file.split('/'), `${where}: the file must be relative to the package root, inside it`).not.toContain(
          '..',
        );
        const node = lookUpTokenPath(build.buildDir, file, tokenPath);
        expect(
          typeof node === 'object' && node !== null && '$value' in node,
          `${where}: ${file}#${tokenPath} must resolve to a token in the built package`,
        ).toBe(true);
        expect(tokenPath.split('.').at(-1), `${where}: the token path must end in the leaf key`).toBe(
          declaration.name.slice(2),
        );
      }
    }
  });

  // TOK-159, TOK-050, spike #7 results 5 and 8
  it('TOK-159: each source comment names the file of the block context, including component files outside tokens/', () => {
    for (const block of getFixtureBlocks()) {
      const context = classifyBlock(block);
      const expectedSource = new Map(
        tokensOfFiles(filesForBlockContext(context)).map((token) => [`--${token.leaf}`, `${token.file}#${token.path}`]),
      );
      for (const declaration of block.declarations) {
        expect(
          declaration.trailingComment?.trim(),
          `${declaration.name} in the ${context} block must point at the file that declares it for that context`,
        ).toBe(expectedSource.get(declaration.name));
      }
    }
    const rootComments = blocksOf('root')
      .flatMap((block) => block.declarations)
      .map((declaration) => declaration.trailingComment?.trim());
    expect(rootComments).toContain(
      'src/components/button/button.tokens.json#button.ui-button__color-bg-primary-default',
    );
    expect(rootComments).toContain(
      'src/components/dialog/dialog.tokens.json#dialog.trigger.ui-dialog__trigger__color-fg-default',
    );
  });

  // TOK-045, TOK-058: an alias stays a var() reference, so a component token follows the active theme
  it('TOK-058: every alias is written as var(-- plus the target leaf key), so component tokens follow the active theme', () => {
    let aliasCount = 0;
    for (const block of getFixtureBlocks()) {
      const tokens = new Map(
        tokensOfFiles(filesForBlockContext(classifyBlock(block))).map((token) => [`--${token.leaf}`, token]),
      );
      for (const declaration of block.declarations) {
        const target = aliasTargetLeaf(tokens.get(declaration.name)?.token.$value);
        if (target === undefined) continue;
        aliasCount += 1;
        expect(declaration.value, `${declaration.name} aliases ${target}`).toBe(`var(--${target})`);
      }
    }
    expect(aliasCount, 'fixture precondition: the fixture has aliases').toBeGreaterThan(0);
  });
});

describe('token pipeline: failure modes', { timeout: buildTimeoutMs }, () => {
  const missingAliasCases = [
    {
      label: 'a semantic token in the default theme file',
      file: 'tokens/theme/light.tokens.json',
      from: '{ref.color.ui-ref-color-gray-50}',
      to: '{ref.color.ui-ref-color-gray-1000}',
    },
    {
      label: 'a semantic token in a non-default theme file',
      file: 'tokens/theme/dark.tokens.json',
      from: '{ref.color.ui-ref-color-gray-950}',
      to: '{ref.color.ui-ref-color-gray-1000}',
    },
    {
      label: 'a component token outside tokens/',
      file: 'src/components/button/button.tokens.json',
      from: '{color.ui-color-bg-accent-default}',
      to: '{color.ui-color-bg-missing-default}',
    },
  ] as const;

  // Failure mode in the issue: an alias to a missing token. TOK-045
  it.each(missingAliasCases)(
    'an alias to a missing token in $label exits non-zero and writes no tokens.css',
    (testCase) => {
      // Control: the unchanged fixture builds, so a non-zero exit below comes from the broken alias.
      const valid = getFixtureBuild();
      expect(valid.run.exitCode, `control: the valid fixture must build. ${describeBuild(valid)}`).toBe(0);

      const broken = buildTokenSystem({
        sourceDir: fixtureSystemDir,
        edit: (buildDir) => {
          const path = join(buildDir, ...testCase.file.split('/'));
          const text = readFileSync(path, 'utf8');
          expect(text.includes(testCase.from), `fixture precondition: ${testCase.file} contains ${testCase.from}`).toBe(
            true,
          );
          writeFileSync(path, text.replace(testCase.from, testCase.to));
        },
      });
      expect(broken.run.exitCode, describeBuild(broken)).not.toBe(0);
      expect(broken.run.exitCode, `the build must exit, not time out. ${describeBuild(broken)}`).not.toBe(-1);
      const missingName = testCase.to.slice(1, -1).split('.').at(-1) ?? '';
      expect(broken.run.output, 'the error must name the missing alias target').toContain(missingName);
      expect(broken.tokensCss, 'a failed build must not write generated/tokens.css').toBeUndefined();
      const generatedFiles = [...broken.filesAfter.keys()].filter((file) => file.startsWith('generated/'));
      expect(generatedFiles, 'a failed build must not write generated files').toEqual([]);
    },
  );
});
