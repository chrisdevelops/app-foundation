// Gate tests for #19: the real foundation tokens in packages/foundation follow
// the spec layout with a minimal set (token profile spec "File layout",
// "Themes, contrast and density", "Token metadata"; ADR 0004 decision 7).
//
// Contract (input and output):
// - Input: packages/foundation/tokens/ui.resolver.json and the token files it
//   names, in tokens/ and src/components/<block>/.
// - Minimal set: at least one primitive, one semantic colour in all four
//   theme files, and one semantic dimension in both density files.
// - Colours are authored in `oklch` and lie inside sRGB. Every token has
//   `$type` and `$description`; semantic and component tokens also have
//   `usage` in the profile extension. (Token lint enforces these in phase 2;
//   this gate checks the files as they are.)
// - Output: `tz build` on a copy of these files writes generated/tokens.css;
//   the package script `tokens:build` (`tz build`) in packages/foundation
//   itself writes it too; and generated/tokens.css is committed with the header.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { isOklchInsideSrgb } from './test-support/oklch-gamut';
import {
  buildTokenSystem,
  describeBuild,
  foundationDir,
  listFilesRelative,
  removeTokenBuildDirs,
  runFoundationTokensBuildInPlace,
  type TokenBuildResult,
} from './test-support/token-build';
import { parseTokenCss } from './test-support/token-css';
import {
  aliasTargetLeaf,
  lookUpTokenPath,
  profileExtensionKey,
  readResolver,
  readTokenFile,
  resolverFiles,
  type ResolverDocument,
  type SourceToken,
} from './test-support/token-sources';

const generatedHeader = '/* GENERATED by tz build. Edit the source *.tokens.json files, never this file. */';
const themeContexts = ['light', 'dark', 'light-high-contrast', 'dark-high-contrast'] as const;
const densityContexts = ['compact', 'comfortable'] as const;
const specRefFiles = ['color', 'space', 'font', 'motion'].map((name) => `tokens/ref/${name}.tokens.json`);
const specSysFiles = ['tokens/sys/base.tokens.json'];
const componentFilePattern = /^src\/components\/([a-z0-9-]+)\/([a-z0-9-]+)\.tokens\.json$/;

const resolverPath = join(foundationDir, 'tokens', 'ui.resolver.json');

/** The foundation resolver; fails with the contract text when it does not exist yet. */
function loadFoundationResolver(): ResolverDocument {
  expect(existsSync(resolverPath), 'packages/foundation/tokens/ui.resolver.json must exist (TOK-050, TOK-051)').toBe(
    true,
  );
  return readResolver(foundationDir);
}

function loadFoundationFiles(): ReturnType<typeof resolverFiles> {
  return resolverFiles(loadFoundationResolver());
}

function allResolverFiles(files: ReturnType<typeof resolverFiles>): string[] {
  return [
    ...[...files.sets.values()].flat(),
    ...[...files.contexts.values()].flatMap((contexts) => [...contexts.values()].flat()),
  ];
}

function readFoundationTokens(files: readonly string[]): SourceToken[] {
  return files.flatMap((file) => readTokenFile(foundationDir, file));
}

function allFoundationTokens(): SourceToken[] {
  const files = allResolverFiles(loadFoundationFiles());
  for (const file of files) {
    expect(existsSync(join(foundationDir, ...file.split('/'))), `${file} named by the resolver must exist`).toBe(true);
  }
  return readFoundationTokens(files);
}

let foundationBuild: TokenBuildResult | undefined;

/** Builds a copy of the real foundation token files with the real config. */
function getFoundationBuild(): TokenBuildResult {
  const files = listFilesRelative(foundationDir).filter(
    (file) =>
      (file.startsWith('tokens/') && (file.endsWith('.tokens.json') || file.endsWith('.resolver.json'))) ||
      componentFilePattern.test(file),
  );
  foundationBuild ??= buildTokenSystem({ sourceDir: foundationDir, files });
  return foundationBuild;
}

afterAll(() => {
  removeTokenBuildDirs();
});

describe('foundation tokens: spec layout', () => {
  // TOK-050, TOK-051
  it('TOK-051: tokens/ holds ui.resolver.json and *.tokens.json files in ref/, sys/, theme/ and density/ only, each named by the resolver', () => {
    const files = loadFoundationFiles();
    const named = new Set(allResolverFiles(files));
    const onDisk = readdirSync(join(foundationDir, 'tokens'), { recursive: true, withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => `${join(entry.parentPath, entry.name).slice(foundationDir.length).split('\\').join('/')}`);
    for (const file of onDisk) {
      if (file === 'tokens/ui.resolver.json') continue;
      expect(file, 'token files use the .tokens.json extension inside the spec folders').toMatch(
        /^tokens\/(ref|sys|theme|density)\/[a-z0-9-]+\.tokens\.json$/,
      );
      expect(named.has(file), `${file} must be named by tokens/ui.resolver.json`).toBe(true);
    }
    for (const file of named) {
      expect(existsSync(join(foundationDir, ...file.split('/'))), `${file} named by the resolver must exist`).toBe(
        true,
      );
    }
  });

  // TOK-050
  it('TOK-050: the ref set names spec primitive files, the sys set names sys/base, and component files sit beside their component', () => {
    const files = loadFoundationFiles();
    const refFiles = files.sets.get('ref') ?? [];
    expect(refFiles.length, 'the ref set must name at least one file').toBeGreaterThan(0);
    for (const file of refFiles) expect(specRefFiles, `ref set file ${file}`).toContain(file);
    for (const file of files.sets.get('sys') ?? []) expect(specSysFiles, `sys set file ${file}`).toContain(file);
    for (const file of files.sets.get('components') ?? []) {
      const match = componentFilePattern.exec(file);
      expect(match, `component file ${file} must be src/components/<block>/<block>.tokens.json`).not.toBeNull();
      expect(match?.[1], `component file ${file} must be named after its folder`).toBe(match?.[2]);
    }
  });

  // TOK-056, TOK-058
  it('TOK-056: the resolver has the ref, sys and components sets, the theme and density modifiers, and resolves components last', () => {
    const resolver = loadFoundationResolver();
    expect(resolver.version).toBe('2025.10');
    expect(Object.keys(resolver.sets ?? {}).sort()).toEqual(['components', 'ref', 'sys']);
    expect(Object.keys(resolver.modifiers ?? {}).sort()).toEqual(['density', 'theme']);
    const files = resolverFiles(resolver);
    expect(Object.fromEntries(files.contexts.get('theme') ?? [])).toEqual(
      Object.fromEntries(themeContexts.map((context) => [context, [`tokens/theme/${context}.tokens.json`]])),
    );
    expect(Object.fromEntries(files.contexts.get('density') ?? [])).toEqual(
      Object.fromEntries(densityContexts.map((context) => [context, [`tokens/density/${context}.tokens.json`]])),
    );
    expect(resolver.modifiers?.theme?.default).toBe('light');
    expect(resolver.modifiers?.density?.default).toBe('compact');
    expect((resolver.resolutionOrder ?? []).map((item) => item.$ref)).toEqual([
      '#/sets/ref',
      '#/sets/sys',
      '#/modifiers/theme',
      '#/modifiers/density',
      '#/sets/components',
    ]);
  });

  // TOK-056: one modifier per $type
  it('TOK-056: theme files hold only colour tokens and density files only dimension tokens', () => {
    const files = loadFoundationFiles();
    for (const context of themeContexts) {
      for (const token of readFoundationTokens(files.contexts.get('theme')?.get(context) ?? [])) {
        expect(token.token.$type, `${token.file}#${token.path}`).toBe('color');
      }
    }
    for (const context of densityContexts) {
      for (const token of readFoundationTokens(files.contexts.get('density')?.get(context) ?? [])) {
        expect(token.token.$type, `${token.file}#${token.path}`).toBe('dimension');
      }
    }
  });
});

describe('foundation tokens: minimal set', () => {
  // TOK-002, TOK-037
  it('TOK-002: the ref set has at least one primitive with a literal value', () => {
    const files = loadFoundationFiles();
    const primitives = readFoundationTokens(files.sets.get('ref') ?? []).filter(
      (token) => token.tier === 'primitive' && aliasTargetLeaf(token.token.$value) === undefined,
    );
    expect(primitives.length, 'at least one ui-ref-* token with a literal $value').toBeGreaterThan(0);
  });

  // TOK-036, TOK-059 to TOK-062
  it('TOK-036: at least one semantic colour is declared in all four theme files', () => {
    const files = loadFoundationFiles();
    const leavesPerTheme = themeContexts.map(
      (context) =>
        new Set(
          readFoundationTokens(files.contexts.get('theme')?.get(context) ?? [])
            .filter((token) => token.tier === 'semantic' && token.token.$type === 'color')
            .map((token) => token.leaf),
        ),
    );
    const inAll = [...(leavesPerTheme[0] ?? [])].filter((leaf) => leavesPerTheme.every((leaves) => leaves.has(leaf)));
    expect(inAll.length, 'semantic colours present in light, dark and both high contrast files').toBeGreaterThan(0);
  });

  // TOK-036, TOK-063
  it('TOK-036: at least one semantic dimension is declared in both density files', () => {
    const files = loadFoundationFiles();
    const leavesPerDensity = densityContexts.map(
      (context) =>
        new Set(
          readFoundationTokens(files.contexts.get('density')?.get(context) ?? [])
            .filter((token) => token.tier === 'semantic' && token.token.$type === 'dimension')
            .map((token) => token.leaf),
        ),
    );
    const inBoth = [...(leavesPerDensity[0] ?? [])].filter((leaf) =>
      leavesPerDensity.every((leaves) => leaves.has(leaf)),
    );
    expect(inBoth.length, 'semantic dimensions present in compact and comfortable').toBeGreaterThan(0);
  });

  // TOK-135, ADR 0004 decision 7
  it('TOK-135: every literal colour is authored in oklch and lies inside sRGB', () => {
    // Control for the gamut check (spike #7 gamut facts).
    expect(isOklchInsideSrgb(0.55, 0.2, 260), 'control: oklch(0.55 0.2 260) is inside sRGB').toBe(true);
    expect(isOklchInsideSrgb(0.6, 0.2, 255), 'control: oklch(0.6 0.2 255) is outside sRGB').toBe(false);

    const literalColours = allFoundationTokens().filter(
      (token) => token.token.$type === 'color' && aliasTargetLeaf(token.token.$value) === undefined,
    );
    expect(literalColours.length, 'the minimal set has at least one literal colour').toBeGreaterThan(0);
    for (const token of literalColours) {
      const where = `${token.file}#${token.path}`;
      const value = token.token.$value as { colorSpace?: unknown; components?: unknown };
      expect(value.colorSpace, `${where} must be authored in oklch`).toBe('oklch');
      const components = Array.isArray(value.components) ? (value.components as unknown[]) : [];
      expect(
        components.length === 3 && components.every((part) => typeof part === 'number'),
        `${where} must have three numeric oklch components`,
      ).toBe(true);
      const [l, c, h] = components as [number, number, number];
      expect(isOklchInsideSrgb(l, c, h), `${where} oklch(${l} ${c} ${h}) must lie inside sRGB`).toBe(true);
    }
  });

  // Issue #19 criterion; TOK-097 to TOK-099 and TOK-104 (lint enforcement in phase 2)
  it('TOK-097: every token has $type and $description, and semantic and component tokens have usage', () => {
    const tokens = allFoundationTokens();
    expect(tokens.length).toBeGreaterThan(0);
    for (const token of tokens) {
      const where = `${token.file}#${token.path}`;
      expect(typeof token.token.$type === 'string' && token.token.$type !== '', `${where} must have $type`).toBe(true);
      expect(
        typeof token.token.$description === 'string' && token.token.$description.trim() !== '',
        `${where} must have a $description`,
      ).toBe(true);
      if (token.tier === 'primitive') continue;
      const extensions = token.token.$extensions as Record<string, { usage?: unknown } | undefined> | undefined;
      const usage = extensions?.[profileExtensionKey]?.usage;
      expect(
        typeof usage === 'string' && usage.trim() !== '',
        `${where} (${token.tier}) must have $extensions["${profileExtensionKey}"].usage`,
      ).toBe(true);
    }
  });
});

describe('foundation tokens: tz build', { timeout: 240_000 }, () => {
  // TOK-111 (tokens.css part), TOK-112, TOK-157, TOK-159
  it('TOK-111: tz build on the foundation tokens writes tokens.css with the header, a variable per token and a resolving source comment on each line', () => {
    const tokens = allFoundationTokens();
    const build = getFoundationBuild();
    expect(build.run.exitCode, describeBuild(build)).toBe(0);
    expect(build.tokensCss, `generated/tokens.css was not written. ${describeBuild(build)}`).toBeDefined();
    const css = (build.tokensCss ?? Buffer.alloc(0)).toString('utf8');
    expect(css.split('\n')[0]).toBe(generatedHeader);
    const parsed = parseTokenCss(css);
    expect(parsed.problems).toEqual([]);
    const declarations = parsed.blocks.flatMap((block) => block.declarations);
    const names = new Set(declarations.map((declaration) => declaration.name));
    for (const token of tokens)
      expect(names.has(`--${token.leaf}`), `tokens.css must declare --${token.leaf}`).toBe(true);
    for (const declaration of declarations) {
      const match = /^ ([^\s#]+)#([^\s#]+) $/.exec(declaration.trailingComment ?? '');
      expect(match, `line ${declaration.line} (${declaration.name}) must end with a source comment`).not.toBeNull();
      const node = lookUpTokenPath(build.buildDir, match?.[1] ?? '', match?.[2] ?? '');
      expect(
        typeof node === 'object' && node !== null && '$value' in node,
        `line ${declaration.line}: ${match?.[1]}#${match?.[2]} must resolve to a token`,
      ).toBe(true);
    }
  });

  // TOK-111, TOK-112: the package's own token build script (`tokens:build`,
  // which is `tz build`) runs in packages/foundation itself, not only in a
  // copy, on every CI platform (#19 attempt 2: Windows). The helper moves the
  // committed generated/ aside for the build and moves it back afterwards.
  it('TOK-111: pnpm run tokens:build in packages/foundation itself writes generated/tokens.css with the header and a variable per token', () => {
    const tokens = allFoundationTokens();
    const build = runFoundationTokensBuildInPlace();
    const described = `\`${build.run.command}\` in packages/foundation exited ${build.run.exitCode}:\n${build.run.output.slice(-4000)}`;
    expect(build.run.exitCode, described).toBe(0);
    expect(build.tokensCss, `generated/tokens.css was not written. ${described}`).toBeDefined();
    const css = (build.tokensCss ?? Buffer.alloc(0)).toString('utf8');
    expect(css.split('\n')[0]).toBe(generatedHeader);
    const parsed = parseTokenCss(css);
    expect(parsed.problems).toEqual([]);
    const names = new Set(parsed.blocks.flatMap((block) => block.declarations.map((declaration) => declaration.name)));
    for (const token of tokens)
      expect(names.has(`--${token.leaf}`), `tokens.css must declare --${token.leaf}`).toBe(true);
  });

  // TOK-111: committed, with the header (the drift check against a fresh build is TOK-151, phase 2)
  it('TOK-111: packages/foundation/generated/tokens.css exists and starts with the generated header', () => {
    const committed = join(foundationDir, 'generated', 'tokens.css');
    expect(existsSync(committed), 'packages/foundation/generated/tokens.css must be committed').toBe(true);
    expect(readFileSync(committed, 'utf8').split(/\r?\n/)[0]).toBe(generatedHeader);
  });
});
