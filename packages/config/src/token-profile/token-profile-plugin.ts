// The token profile's Terrazzo plugin (ADR 0006 item 4; token profile spec,
// "Generated outputs" > "tokens.css"; TOK-112, TOK-115 to TOK-118).
//
// Input: a resolver (`config.tokens`) plus the `*.tokens.json` files it names,
// and the CSS transforms of @terrazzo/plugin-css run with
// `tokenProfileCssPluginOptions` (spike #7 result 10).
// Output: `tokens.css` in Terrazzo's `outDir`, or a build error that names the
// problem; on an error Terrazzo writes no files.
//
// Use in a terrazzo.config.ts:
//   plugins: [css(tokenProfileCssPluginOptions), tokenProfilePlugin({ packageRoot: new URL('./', import.meta.url) })]
import type { defineConfig } from '@terrazzo/cli';
import type { CSSPluginOptions } from '@terrazzo/plugin-css';
import { tokenProfileBlocks, tokenProfilePermutations, wrapTokenProfileBlock } from './token-profile-contexts';
import {
  indexTokenDeclarations,
  isDeclarationActive,
  TokenSourceIndexError,
  winningDeclaration,
  type TokenDeclaration,
} from './token-source-index';

type TerrazzoPlugin = NonNullable<Parameters<typeof defineConfig>[0]['plugins']>[number];

/** The plugin's name in Terrazzo's plugin list and log lines. */
export const tokenProfilePluginName = '@foundation/config/token-profile';

/** Line 1 of tokens.css (TOK-118, ADR 0002 item 8). */
export const generatedTokensCssHeader =
  '/* GENERATED by tz build. Edit the source *.tokens.json files, never this file. */';

/** Name of the CSS file the plugin writes in `outDir` (TOK-111, TOK-112). */
const tokensCssFileName = 'tokens.css';

/** The CSS variable of a token: `--` plus its leaf key (TOK-012, TOK-115). */
const variableNameOfTokenId = (id: string): string => `--${id.split('.').at(-1)}`;

/**
 * Options for `@terrazzo/plugin-css`: it computes the values for each
 * context and writes no file (TOK-112); the profile plugin writes tokens.css.
 */
export const tokenProfileCssPluginOptions: CSSPluginOptions = {
  skipBuild: true,
  variableName: (token) => variableNameOfTokenId(token.id),
  permutations: tokenProfilePermutations(),
};

export interface TokenProfilePluginOptions {
  /** Folder that source comments are relative to: the package that holds terrazzo.config.ts. */
  readonly packageRoot: URL;
}

const compareIds = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

export function tokenProfilePlugin(options: TokenProfilePluginOptions): TerrazzoPlugin {
  let resolverUrl: URL | undefined;
  return {
    name: tokenProfilePluginName,
    config(config) {
      resolverUrl = config.tokens.find((url) => url.pathname.endsWith('.resolver.json'));
    },
    build({ context, getTransforms, outputFile }) {
      const fail = (message: string): never => {
        context.logger.error({ group: 'plugin', label: tokenProfilePluginName, message });
        throw new Error(`${tokenProfilePluginName}: ${message}`);
      };
      if (!resolverUrl) return fail('config.tokens must name a *.resolver.json file (TOK-050, TOK-056)');
      let declarations: TokenDeclaration[] = [];
      try {
        declarations = indexTokenDeclarations(resolverUrl, options.packageRoot);
      } catch (error) {
        if (!(error instanceof TokenSourceIndexError)) throw error;
        fail(`${resolverUrl.pathname}: ${error.message}`);
      }

      const blocks: string[] = [];
      for (const block of tokenProfileBlocks) {
        const scope = block.scope;
        const inScope = (id: string): boolean =>
          scope.kind === 'all'
            ? declarations.some((declaration) => declaration.id === id && isDeclarationActive(declaration, block.input))
            : declarations.some(
                (declaration) =>
                  declaration.id === id &&
                  declaration.origin.kind === 'modifier' &&
                  declaration.origin.modifier === scope.modifier &&
                  declaration.origin.context === scope.context,
              );
        const expectedIds = [...new Set(declarations.map((declaration) => declaration.id))].filter(inScope);
        if (expectedIds.length === 0) continue;

        const transforms = new Map(
          getTransforms({ format: 'css', input: { ...block.input } }).map((transform) => [
            transform.token.id,
            transform,
          ]),
        );
        const lines = expectedIds.sort(compareIds).map((id) => {
          const transform = transforms.get(id);
          if (!transform) {
            return fail(
              `${id} has no CSS value for ${JSON.stringify(block.input)}; run @terrazzo/plugin-css with tokenProfileCssPluginOptions`,
            );
          }
          if (transform.localID !== variableNameOfTokenId(id)) {
            return fail(`${id} has the CSS name ${transform.localID}; expected ${variableNameOfTokenId(id)} (TOK-115)`);
          }
          // DEFERRED: TOK-135 (wide-gamut colours give one value per gamut; the srgb gamut lint is #20)
          if (typeof transform.value !== 'string') {
            return fail(`${id} has a CSS value per gamut or sub-value; tokens.css takes one value per token`);
          }
          const source = winningDeclaration(declarations, id, block.input);
          if (!source) return fail(`${id} has no source file for ${JSON.stringify(block.input)}`);
          return `${transform.localID}: ${transform.value}; /* ${source.file}#${source.id} */`;
        });
        blocks.push(wrapTokenProfileBlock(block, lines.join('\n')));
      }

      outputFile(tokensCssFileName, `${generatedTokensCssHeader}\n\n${blocks.join('\n\n')}\n`);
      // DEFERRED: TOK-092, TOK-113, TOK-119, TOK-160 (generated/token-names.ts; phase 2)
      // DEFERRED: TOK-114, TOK-120, TOK-121, TOK-122, TOK-123, TOK-124, TOK-125, TOK-126, TOK-127 (generated/TOKENS.md; phase 2)
    },
  };
}
